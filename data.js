/**
 * 热量红绿灯分级（以每100g热量为准）
 * green: <= 100 kcal (低卡推荐)
 * yellow: 101 - 250 kcal (适量食用)
 * red: > 250 kcal (高卡控量)
 */
function getCalorieLevel(kcalPer100g) {
  if (kcalPer100g <= 100) {
    return { key: 'green', label: '低卡', badgeText: '🟢 绿灯低卡', desc: '热量较低，适合减脂期放心搭配' };
  }
  if (kcalPer100g <= 250) {
    return { key: 'yellow', label: '适中', badgeText: '🟡 黄灯适中', desc: '热量适中，注意控制整体份量' };
  }
  return { key: 'red', label: '高卡', badgeText: '🔴 红灯高卡', desc: '能量密度较高，建议浅尝控制份量' };
}

